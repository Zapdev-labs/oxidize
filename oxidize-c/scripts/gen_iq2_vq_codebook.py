def extract(text: str) -> list[int]:
    match = re.search(
        r"GGML_TABLE_BEGIN\(int8_t,\s*iq2vq_codebook,\s*(\d+)\)(.*?)GGML_TABLE_END\(\)",
        text,
        re.DOTALL,
    )
    if match is None:
        sys.exit("iq2vq_codebook table not found")
    values = [int(v) for v in re.findall(r"-?\d+", match.group(2))]
    if int(match.group(1)) != VALUES or len(values) != VALUES:
        sys.exit(f"expected {VALUES} codebook values, found {len(values)}")
    if any(v < -128 or v > 127 for v in values):
        sys.exit("codebook value outside int8 range")
    return values


def fnv1a64(values: list[int]) -> int:
    h = 14695981039346656037
    for v in values:
        h ^= v & 0xFF
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def render(values: list[int]) -> str:
    rows = [
        "    " + ", ".join(str(v) for v in values[i : i + PER_LINE]) + ","
        for i in range(0, len(values), PER_LINE)
    ]
    return (
        HEADER.format(fingerprint=f"0x{fnv1a64(values):016x}")
        + f"const int8_t oc_iq2_vq_codebook[{VALUES}] = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("ggml_common_h", type=Path)
    parser.add_argument("--check", action="store_true",
                        help="fail if src/compute/iq2_vq.c is out of date")
    args = parser.parse_args()
    values = extract(args.ggml_common_h.read_text())
    rendered = render(values)
    print(f"fnv1a64 0x{fnv1a64(values):016x}")
    if args.check:
        if OUT.read_text() != rendered:
            sys.exit(f"{OUT} does not match {args.ggml_common_h}")
        print(f"{OUT} is up to date")
        return
    OUT.write_text(rendered)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
