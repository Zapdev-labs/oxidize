#!/usr/bin/env python3
"""Generate oxidize-c/src/compute/iq2_vq.c from a ggml-common.h with IQ2_VQ.

IQ2_VQ (GGML type 70) is not part of upstream ggml. Its codebook is the
iq2vq_codebook table in ggml/src/ggml-common.h of the llama.cpp-bigmoe fork
(bigmoe branch of github.com/Jackson57279/llama.cpp).

Run:   python3 scripts/gen_iq2_vq_codebook.py PATH/TO/ggml-common.h
Check: python3 scripts/gen_iq2_vq_codebook.py PATH/TO/ggml-common.h --check
"""
