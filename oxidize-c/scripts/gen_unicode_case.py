#!/usr/bin/env python3
"""Generate src/util/unicode_case.c: letter-case ranges (Lu|Lt and Ll) for
pre-tokenizers that split on letter case (o200k / gpt-4o).

Usage: python3 scripts/gen_unicode_case.py > src/util/unicode_case.c
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(unicodedata.category(chr(cp)))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"const size_t {name}_n = {len(rs)};")
    print(f"const uint32_t {name}[][2] = {{")
    for a, b in rs:
        print(f"    {{ 0x{a:05X}u, 0x{b:05X}u }},")
    print("};\n")


print("/* unicode_case.c — generated by scripts/gen_unicode_case.py from Python")
print(f" * unicodedata {unicodedata.unidata_version}. Do not edit by hand. */")
print('#include "oxidize/unicode.h"\n')
emit("oc_unicode_upper_ranges", ranges(lambda c: c in ("Lu", "Lt")))
emit("oc_unicode_lower_ranges", ranges(lambda c: c == "Ll"))
print("""static bool in_ranges(const uint32_t (*r)[2], size_t n, uint32_t cp)
{
    size_t lo = 0, hi = n;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (cp < r[mid][0]) hi = mid;
        else if (cp > r[mid][1]) lo = mid + 1;
        else return true;
    }
    return false;
}

bool oc_unicode_is_upper(uint32_t cp)
{
    return in_ranges(oc_unicode_upper_ranges, oc_unicode_upper_ranges_n, cp);
}

bool oc_unicode_is_lower(uint32_t cp)
{
    return in_ranges(oc_unicode_lower_ranges, oc_unicode_lower_ranges_n, cp);
}""")
